-- Хранимая форма зеркалит src/killswitch/haltState.ts::HaltState один в один
-- (haltNew/flattenAll/reason/setBy/setAtMs) — эта таблица не вводит новую модель
-- состояния, только персистентность уже существующей чистой модели.
--
-- Singleton через CHECK (id = 1), а НЕ "последняя строка по timestamp":
-- halt-состояние обязано быть ОДНОЗНАЧНЫМ в любой момент — у бота не может быть
-- двух конкурирующих ответов на вопрос "мы сейчас halted?". Подход "последняя
-- по timestamp" требует ORDER BY + LIMIT 1 на каждом чтении (лишняя возможность
-- прочитать не то при рассинхроне часов/индекса) и не закрывает гонку на записи:
-- два параллельных INSERT'а новой "текущей" строки оба успешно закоммитятся как
-- отдельные строки, и какая из них "текущая" становится вопросом порядка чтения,
-- а не гарантией схемы. CHECK (id = 1) вместе с ровно одной строкой, вставленной
-- ниже, делает вторую строку физически невозможной: INSERT с любым другим id
-- нарушает CHECK, INSERT с id = 1 нарушает PRIMARY KEY. Однозначность состояния
-- гарантирует сама схема, а не дисциплина вызывающего кода.
CREATE TABLE halt_state (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1), -- singleton-таблица: ровно одна строка на весь бот
  halt_new boolean NOT NULL DEFAULT false,
  flatten_all boolean NOT NULL DEFAULT false,
  reason text,
  set_by text,
  -- Машинная метка времени в мс (Date.now() на стороне приложения при вызове
  -- applyHaltNew/applyFlattenAll) — тот же bigint-мс паттерн, что и у биржевых
  -- меток в market-data-таблицах, но источник здесь наш собственный процесс,
  -- а не Bybit. NULL, пока halt ни разу не устанавливался в текущем цикле
  -- (совпадает с HaltState.setAtMs: number | null).
  set_at_ms bigint,
  -- Время последней записи ЭТОЙ строки БД (не бизнес-событие, а служебный
  -- аудит-штамп) — та же роль, что у fetched_at в market-data-таблицах, но
  -- здесь строка ровно одна и переиспользуется, а не вставляется заново на
  -- каждое наблюдение. DEFAULT now() закрывает только начальную INSERT ниже:
  -- Postgres не переисполняет DEFAULT-выражение колонки при UPDATE (это не
  -- триггер) — на каждое сохранение значение обязана явно проставлять
  -- saveHaltState.
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Единственная строка на весь бот: создаётся здесь и никогда не удаляется и не
-- пересоздаётся. loadHaltState/saveHaltState в рантайме работают только через
-- SELECT/UPDATE ... WHERE id = 1 — INSERT в этой таблице после миграции не
-- происходит никогда.
INSERT INTO halt_state (id) VALUES (1);

